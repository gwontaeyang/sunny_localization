import argparse
import json
import os
from pathlib import Path
from typing import Dict, Tuple

import yaml


CoordinateMap = Dict[int, Tuple[float, float]]


def expand_path(path: str) -> str:
    return os.path.abspath(os.path.expandvars(os.path.expanduser(path)))


def load_yaml(path: str):
    with open(path, "r", encoding="utf-8") as file:
        document = yaml.safe_load(file)
    return document if document is not None else {}


def load_yaml_coordinates(path: str) -> CoordinateMap:
    document = load_yaml(path)
    nodes = document.get("nodes", [])
    if not isinstance(nodes, list):
        raise ValueError(f"YAML map has no list-valued 'nodes': {path}")

    coordinates: CoordinateMap = {}
    for node in nodes:
        if not isinstance(node, dict) or "id" not in node:
            continue
        if "x" not in node or "y" not in node:
            continue
        tag_id = int(node["id"])
        coordinates[tag_id] = (float(node["x"]), float(node["y"]))
    return coordinates


def load_json_coordinates(path: str) -> CoordinateMap:
    with open(path, "r", encoding="utf-8") as file:
        document = json.load(file)

    tags = document.get("tags", [])
    if not isinstance(tags, list):
        raise ValueError(f"JSON tag map has no list-valued 'tags': {path}")

    coordinates: CoordinateMap = {}
    for tag in tags:
        if not isinstance(tag, dict) or "id" not in tag:
            continue
        pose = tag.get("pose", {})
        position = pose.get("position", {}) if isinstance(pose, dict) else {}
        if "x" not in position or "y" not in position:
            continue
        tag_id = int(tag["id"])
        coordinates[tag_id] = (float(position["x"]), float(position["y"]))
    return coordinates


def load_measured_coordinates(path: str) -> CoordinateMap:
    suffix = Path(path).suffix.lower()
    if suffix == ".json":
        return load_json_coordinates(path)
    return load_yaml_coordinates(path)


def merge_nodes(base_document, measured: CoordinateMap, add_missing: bool):
    nodes = base_document.get("nodes", [])
    if not isinstance(nodes, list):
        raise ValueError("Base map has no list-valued 'nodes'")

    base_ids = set()
    updated_ids = []
    unchanged_ids = []

    for node in nodes:
        if not isinstance(node, dict) or "id" not in node:
            continue
        tag_id = int(node["id"])
        base_ids.add(tag_id)
        if tag_id not in measured:
            unchanged_ids.append(tag_id)
            continue
        x, y = measured[tag_id]
        node["x"] = float(x)
        node["y"] = float(y)
        updated_ids.append(tag_id)

    missing_from_base = sorted(set(measured.keys()) - base_ids)
    if add_missing:
        for tag_id in missing_from_base:
            x, y = measured[tag_id]
            nodes.append({"id": tag_id, "x": float(x), "y": float(y)})

    return {
        "updated": sorted(updated_ids),
        "left_unchanged": sorted(unchanged_ids),
        "missing_from_base": missing_from_base,
        "added": missing_from_base if add_missing else [],
    }


def write_yaml(path: str, document) -> None:
    output_dir = os.path.dirname(path)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
    with open(path, "w", encoding="utf-8") as file:
        yaml.safe_dump(
            document,
            file,
            sort_keys=False,
            allow_unicode=True,
            default_flow_style=False,
        )


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Replace node x/y coordinates in an existing tag_map_db YAML while "
            "preserving its graph edges and other top-level fields."
        )
    )
    parser.add_argument(
        "--base",
        required=True,
        help="Existing operational tag_map_db YAML whose edges should be preserved.",
    )
    parser.add_argument(
        "--measured",
        required=True,
        help="Measured tag map YAML or JSON generated by create_tag_map.",
    )
    parser.add_argument(
        "--output",
        required=True,
        help="Output YAML path. Use a new file first; overwrite requires --force.",
    )
    parser.add_argument(
        "--add-missing",
        action="store_true",
        help="Append measured tag IDs that do not exist in the base map. Edges are not generated.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Allow overwriting an existing output file.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the merge summary without writing output.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    base_path = expand_path(args.base)
    measured_path = expand_path(args.measured)
    output_path = expand_path(args.output)

    base_document = load_yaml(base_path)
    measured = load_measured_coordinates(measured_path)
    summary = merge_nodes(base_document, measured, args.add_missing)

    print(f"base: {base_path}")
    print(f"measured: {measured_path}")
    print(f"updated nodes: {len(summary['updated'])} {summary['updated']}")
    print(f"base nodes left unchanged: {len(summary['left_unchanged'])} {summary['left_unchanged']}")
    print(f"measured nodes missing from base: {len(summary['missing_from_base'])} {summary['missing_from_base']}")
    if args.add_missing:
        print(f"added nodes without edges: {len(summary['added'])} {summary['added']}")

    if args.dry_run:
        print("dry-run: output was not written")
        return

    if os.path.exists(output_path) and not args.force:
        raise FileExistsError(
            f"Output already exists: {output_path}. Pass --force to overwrite."
        )

    write_yaml(output_path, base_document)
    print(f"wrote: {output_path}")


if __name__ == "__main__":
    main()
